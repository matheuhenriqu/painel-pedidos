-- ============================================================================
-- PROCEDIMENTO DE TESTE / AVALIAÇÃO ACADÊMICA: PROMOVER USUÁRIO A ADMIN
-- Permite ao avaliador/professor promover qualquer conta criada a Administrador
-- com apenas uma linha no SQL Editor do Supabase:
--   SELECT promover_usuario_admin('professor@exemplo.com');
-- ============================================================================
CREATE OR REPLACE FUNCTION promover_usuario_admin(p_email TEXT)
RETURNS TEXT
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, auth, pg_temp
AS $$
DECLARE
  v_user_id UUID;
BEGIN
  SELECT id INTO v_user_id FROM auth.users WHERE LOWER(email) = LOWER(TRIM(p_email));
  IF v_user_id IS NULL THEN
    RETURN 'Usuário com o e-mail "' || TRIM(p_email) || '" não foi encontrado no sistema auth.users. Crie a conta antes no painel.';
  END IF;

  UPDATE auth.users
  SET raw_app_meta_data = COALESCE(raw_app_meta_data, '{}'::jsonb) || '{"role": "admin"}'::jsonb
  WHERE id = v_user_id;

  RETURN 'Sucesso: Usuário "' || TRIM(p_email) || '" promovido a Administrador! Faça logout e login no painel para aplicar o novo cargo.';
END;
$$;

